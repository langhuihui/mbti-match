// ============================================================
// 辅助函数：获取关系键（处理对称组合）
// 例如：ENNEAGRAM_RELATIONS['3-1'] 会自动查找 '1-3'
// ============================================================
function getEnneagramRelation(typeA, typeB) {
  if (typeA === typeB) {
    return ENNEAGRAM_RELATIONS[`${typeA}-${typeB}`]
  }
  // 尝试两种顺序
  return ENNEAGRAM_RELATIONS[`${typeA}-${typeB}`] ||
         ENNEAGRAM_RELATIONS[`${typeB}-${typeA}`] ||
         { type: 'neutral', desc: '中性关系：差异适中，无明显共鸣或张力' }
}

// ============================================================
// 辅助函数：根据主型编号获取完整数据
// ============================================================
function getEnneagramType(id) {
  return ENNEAGRAM_TYPES[id]
}

// ============================================================
// 辅助函数：根据侧翼 ID 获取数据
// ============================================================
function getEnneagramWing(wingId) {
  return ENNEAGRAM_WINGS.find(w => w.id === wingId)
}

// ============================================================
// 辅助函数：根据主型获取可选侧翼
// ============================================================
function getWingsByType(typeId) {
  return ENNEAGRAM_WINGS.filter(w => w.parentType === typeId)
}

